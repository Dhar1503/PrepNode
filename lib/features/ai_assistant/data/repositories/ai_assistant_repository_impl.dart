/// AI Assistant Repository Implementation
/// Conversation/message bookkeeping is handled by [remoteDataSource] (an
/// in-memory store — see its own doc comment for why). All AI content is
/// generated by [AiResponseEngine] from this device's real local data; no
/// online LLM or remote API is involved anywhere in this class.
class AiAssistantRepositoryImpl implements AiAssistantRepository {
  final MockAiAssistantRemoteDataSource remoteDataSource;
  final AiResponseEngine engine;

  AiAssistantRepositoryImpl({
    required this.remoteDataSource,
    required this.engine,
  });

  @override
  Future<Either<Failure, List<Conversation>>> getConversations(String userId) async {
    try {
      final conversations = await remoteDataSource.getConversations(userId);
      return Right(conversations);
    } catch (e) {
      return Left(const ServerFailure('Failed to get conversations'));
    }
  }

  @override
  Future<Either<Failure, ConversationHistory>> getConversationHistory(
      String conversationId) async {
    try {
      final history = await remoteDataSource.getConversationHistory(conversationId);
      return Right(history);
    } catch (e) {
      return Left(const ServerFailure('Failed to get conversation history'));
    }
  }

  @override
  Future<Either<Failure, Conversation>> createConversation({
    required String userId,
    required String title,
    String? contextModule,
    String? contextId,
  }) async {
    try {
      final conversation = await remoteDataSource.createConversation(
        userId: userId,
        title: title,
        contextModule: contextModule,
        contextId: contextId,
      );
      return Right(conversation);
    } catch (e) {
      return Left(const ServerFailure('Failed to create conversation'));
    }
  }

  @override
  Future<Either<Failure, Conversation>> updateConversation(
    String conversationId, {
    String? title,
    bool? isBookmarked,
  }) async {
    try {
      final conversation = await remoteDataSource.updateConversation(
        conversationId,
        title: title,
        isBookmarked: isBookmarked,
      );
      return Right(conversation);
    } catch (e) {
      return Left(const ServerFailure('Failed to update conversation'));
    }
  }

  @override
  Future<Either<Failure, void>> deleteConversation(String conversationId) async {
    try {
      await remoteDataSource.deleteConversation(conversationId);
      return const Right(null);
    } catch (e) {
      return Left(const ServerFailure('Failed to delete conversation'));
    }
  }

  @override
  Future<Either<Failure, ChatMessage>> sendMessage({
    required String conversationId,
    required String content,
    DoubtContext? context,
  }) async {
    try {
      final userId = await _resolveUserId(conversationId);

      final userMessage = ChatMessage(
        id: 'msg-${DateTime.now().millisecondsSinceEpoch}-u',
        conversationId: conversationId,
        content: content,
        role: MessageRole.user,
        timestamp: DateTime.now(),
      );
      await remoteDataSource.addMessage(conversationId, userMessage);

      final replyText = await engine.reply(userId: userId, message: content);
      final assistantMessage = ChatMessage(
        id: 'msg-${DateTime.now().millisecondsSinceEpoch}-a',
        conversationId: conversationId,
        content: replyText,
        role: MessageRole.assistant,
        timestamp: DateTime.now(),
        metadata: context?.additionalContext,
      );
      await remoteDataSource.addMessage(conversationId, assistantMessage);

      return Right(assistantMessage);
    } catch (e) {
      return Left(const ServerFailure('Failed to send message'));
    }
  }

  @override
  Future<Either<Failure, List<ChatMessage>>> getMessages(
      String conversationId) async {
    try {
      final messages = await remoteDataSource.getMessages(conversationId);
      return Right(messages);
    } catch (e) {
      return Left(const ServerFailure('Failed to get messages'));
    }
  }

  @override
  Stream<ChatMessage> streamMessageResponse({
    required String conversationId,
    required String content,
    DoubtContext? context,
  }) async* {
    final result = await sendMessage(
      conversationId: conversationId,
      content: content,
      context: context,
    );
    final message = result.fold((_) => null, (m) => m);
    if (message != null) yield message;
  }

  /// Looks up which real user a conversation belongs to (set at
  /// createConversation time) rather than adding a userId param to
  /// sendMessage — reuses data already on the Conversation entity.
  Future<String> _resolveUserId(String conversationId) async {
    final match =
        MockAiAssistantRemoteDataSource.conversations.where((c) => c.id == conversationId);
    return match.isNotEmpty ? match.first.userId : '';
  }

  @override
  Future<Either<Failure, List<SuggestedQuestion>>> getSuggestedQuestions({
    String? contextModule,
    String? contextId,
  }) async {
    // Static, but honest: every question here is something the engine can
    // actually answer from real local data (see AiResponseEngine.reply),
    // unlike the previous fabricated syllabus-specific question bank.
    const questions = [
      SuggestedQuestion(
        id: 'sq-weak-areas',
        question: 'What are my weak areas?',
        category: 'revision',
        displayOrder: 1,
        isPopular: true,
      ),
      SuggestedQuestion(
        id: 'sq-plan-today',
        question: "What's on my plan today?",
        category: 'practice',
        displayOrder: 2,
        isPopular: true,
      ),
      SuggestedQuestion(
        id: 'sq-mock-test',
        question: 'How did my last mock test go?',
        category: 'practice',
        displayOrder: 3,
        isPopular: false,
      ),
      SuggestedQuestion(
        id: 'sq-pyq',
        question: "How's my PYQ practice going?",
        category: 'practice',
        displayOrder: 4,
        isPopular: false,
      ),
      SuggestedQuestion(
        id: 'sq-mastery',
        question: "What's my topic mastery?",
        category: 'concept',
        displayOrder: 5,
        isPopular: false,
      ),
      SuggestedQuestion(
        id: 'sq-cutoff',
        question: 'How close am I to the cutoff?',
        category: 'concept',
        displayOrder: 6,
        isPopular: false,
      ),
    ];
    return const Right(questions);
  }

  @override
  Future<Either<Failure, List<AIRecommendation>>> getRecommendations(
      String userId) async {
    try {
      final recommendations = await engine.buildRecommendations(userId);
      return Right(recommendations);
    } catch (e) {
      return Left(const ServerFailure('Failed to get recommendations'));
    }
  }

  @override
  Future<Either<Failure, AIRecommendation>> generateRecommendation({
    required String userId,
    required RecommendationType type,
    String? targetModule,
    String? targetId,
  }) async {
    try {
      final recommendations = await engine.buildRecommendations(userId);
      final match = recommendations.where((r) => r.type == type);
      if (match.isEmpty) {
        return Left(DatabaseFailure.notFound(entity: 'Recommendation of type $type'));
      }
      return Right(match.first);
    } catch (e) {
      return Left(const ServerFailure('Failed to generate recommendation'));
    }
  }

  @override
  Future<Either<Failure, List<AIInsight>>> getInsights(String userId) async {
    try {
      final insights = await engine.buildInsights(userId);
      return Right(insights);
    } catch (e) {
      return Left(const ServerFailure('Failed to get insights'));
    }
  }

  @override
  Future<Either<Failure, AIInsight>> generateInsight({
    required String userId,
    required InsightCategory category,
    Map<String, dynamic>? data,
  }) async {
    try {
      final insights = await engine.buildInsights(userId);
      final match = insights.where((i) => i.category == category);
      if (match.isEmpty) {
        return Left(DatabaseFailure.notFound(entity: 'Insight of category $category'));
      }
      return Right(match.first);
    } catch (e) {
      return Left(const ServerFailure('Failed to generate insight'));
    }
  }

  @override
  Future<Either<Failure, AIInsight>> markInsightActioned(String insightId) async {
    // Insights are computed fresh from live data each call (see
    // buildInsights) rather than stored, and this method isn't given a
    // userId to recompute against — there is no persisted row to flip an
    // isActioned flag on. Not reachable from any screen currently; adding
    // real persistence for this would mean a new stored table, which is
    // out of scope ("no chat history persistence unless already
    // supported").
    return Left(DatabaseFailure.notFound(entity: 'Insight'));
  }

  @override
  Future<Either<Failure, ChatMessage>> explainConcept({
    required String topicId,
    required String conversationId,
    String? userId,
  }) async {
    try {
      final content = await engine.explainConceptText(topicId: topicId, userId: userId);
      return Right(_assistantMessage(conversationId, content, metadata: {'topicId': topicId}));
    } catch (e) {
      return Left(const ServerFailure('Failed to explain concept'));
    }
  }

  @override
  Future<Either<Failure, ChatMessage>> explainAnswer({
    required String questionId,
    required String conversationId,
    bool explainIncorrectOptions = false,
  }) async {
    try {
      // Reuses the same real, template-based PYQ hint (Phase 8) — this
      // module has no separate "full explanation" data source beyond
      // what PracticeSessionScreen's ExplanationPanel already shows.
      final content = await engine.generateHintText(questionId: questionId);
      return Right(_assistantMessage(conversationId, content, metadata: {'questionId': questionId}));
    } catch (e) {
      return Left(const ServerFailure('Failed to explain answer'));
    }
  }

  @override
  Future<Either<Failure, ChatMessage>> generateHint({
    required String questionId,
    required String conversationId,
  }) async {
    try {
      final content = await engine.generateHintText(questionId: questionId);
      return Right(_assistantMessage(conversationId, content, metadata: {'questionId': questionId}));
    } catch (e) {
      return Left(const ServerFailure('Failed to generate hint'));
    }
  }

  @override
  Future<Either<Failure, ChatMessage>> analyzeMistakes({
    required String testResultId,
    required String conversationId,
    String? userId,
  }) async {
    try {
      final resolvedUserId = userId ?? await _resolveUserId(conversationId);
      final content = await engine.analyzeMistakesText(
        testResultId: testResultId,
        userId: resolvedUserId,
      );
      return Right(_assistantMessage(conversationId, content, metadata: {'testResultId': testResultId}));
    } catch (e) {
      return Left(const ServerFailure('Failed to analyze mistakes'));
    }
  }

  @override
  Future<Either<Failure, ChatMessage>> explainAnalytics({
    required String userId,
    required String conversationId,
    String? specificMetric,
  }) async {
    try {
      final content = await engine.reply(
        userId: userId,
        message: specificMetric ?? 'explain my mastery and progress',
      );
      return Right(_assistantMessage(conversationId, content, metadata: {'userId': userId}));
    } catch (e) {
      return Left(const ServerFailure('Failed to explain analytics'));
    }
  }

  @override
  Future<Either<Failure, ChatMessage>> explainReadiness({
    required String examId,
    required String userId,
    required String conversationId,
  }) async {
    try {
      final content = await engine.explainReadinessText(examId: examId, userId: userId);
      return Right(_assistantMessage(conversationId, content, metadata: {'examId': examId, 'userId': userId}));
    } catch (e) {
      return Left(const ServerFailure('Failed to explain readiness'));
    }
  }

  @override
  Future<Either<Failure, List<AIRecommendation>>> recommendResources({
    required String userId,
    String? topicId,
    String? subjectId,
  }) async {
    try {
      final recommendations = await engine.recommendResourcesList(
        userId: userId,
        topicId: topicId,
        subjectId: subjectId,
      );
      return Right(recommendations);
    } catch (e) {
      return Left(const ServerFailure('Failed to recommend resources'));
    }
  }

  @override
  Future<Either<Failure, List<Conversation>>> searchConversations({
    required String userId,
    required String query,
  }) async {
    try {
      final conversations = await remoteDataSource.searchConversations(
        userId: userId,
        query: query,
      );
      return Right(conversations);
    } catch (e) {
      return Left(const ServerFailure('Failed to search conversations'));
    }
  }

  @override
  Future<Either<Failure, List<ChatMessage>>> searchMessages({
    required String conversationId,
    required String query,
  }) async {
    try {
      final messages = await remoteDataSource.searchMessages(
        conversationId: conversationId,
        query: query,
      );
      return Right(messages);
    } catch (e) {
      return Left(const ServerFailure('Failed to search messages'));
    }
  }

  ChatMessage _assistantMessage(
    String conversationId,
    String content, {
    Map<String, dynamic>? metadata,
  }) {
    return ChatMessage(
      id: 'msg-${DateTime.now().millisecondsSinceEpoch}',
      conversationId: conversationId,
      content: content,
      role: MessageRole.assistant,
      timestamp: DateTime.now(),
      metadata: metadata,
    );
  }
}
